/// <summary>
/// Enables logging to the console. Expects that the system can handle UTF-8
/// by default, only very old UNIX systems do not. The caller holds
/// the logging lock.
/// </summary>
bool DebugPrint::Enable_Console_Locked(void)
{
	if (m_ConsoleActive) {
		return true;
	}

	if (!m_DebugInitDone) {
		return false;
	}

	m_ConsoleActive = true;

	if (m_ConsoleReplay.has_value() && !m_ConsoleReplay->empty()) {
		std::cout << *m_ConsoleReplay;
		std::cout.flush();
	}
	m_ConsoleReplay.reset();
	return true;
}
